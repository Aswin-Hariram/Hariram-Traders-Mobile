  async function persistInvoice(showSavedAlert) {
    const currentInvoice = activeInvoice

    try {
      const selectedCustomer = customers.find((customer) => customer.id === currentInvoice.customerId) || null
      const customerSnapshot = selectedCustomer
        ? mapCustomerToInvoiceFields(selectedCustomer)
        : emptyInvoiceCustomerFields
      const normalizedDueDate =
        currentInvoice.dueDate && !isDueDateAfterInvoiceDate(currentInvoice.invoiceDate, currentInvoice.dueDate)
          ? getMinimumDueDate(currentInvoice.invoiceDate)
          : currentInvoice.dueDate

      const savedBill = await saveBill({
        ...currentInvoice,
        dueDate: normalizedDueDate,
        customerId: selectedCustomer?.id || null,
        ...customerSnapshot,
      })

      await refreshRecords({
        billId: savedBill.id,
        customerId: selectedCustomer?.id || customerDraft?.id,
      })
      setInvoice(savedBill)
      scheduleAutomaticBackup()

      if (showSavedAlert) {
        Alert.alert('Bill saved', 'The bill was stored on this device.')
      }

      return savedBill
    } catch (error) {
      Alert.alert('Unable to save bill', error.message || 'Please try again.')
      throw error
    }
  }

  async function persistCustomerDraft(showSavedAlert) {
    const currentCustomer = customerDraft || createCustomer()

    if (!hasCustomerDetails(currentCustomer)) {
      Alert.alert(
        'Customer details required',
        'Add at least one customer detail before saving this profile.'
      )
      return null
    }

    try {
      const savedCustomer = await saveCustomer(currentCustomer)
      await refreshRecords({ customerId: savedCustomer.id })
      setCustomerDraft(savedCustomer)
      scheduleAutomaticBackup()

      if (invoice?.customerId === savedCustomer.id) {
        setInvoice((current) => ({
          ...(current || createDraftBill()),
          ...mapCustomerToInvoiceFields(savedCustomer),
          customerId: savedCustomer.id,
        }))
      }

      if (showSavedAlert) {
        Alert.alert('Customer saved', 'The customer profile was stored on this device.')
      }

      setIsCustomerSheetOpen(false)
      setCustomerSheetMode('view')
      setScreen('launcher')
      setHomeTab('customers')
      return savedCustomer
    } catch (error) {
      Alert.alert('Unable to save customer', error.message || 'Please try again.')
      throw error
    }
  }

