  function scheduleAutomaticBackup() {
    if (autoBackupTimerRef.current) {
      clearTimeout(autoBackupTimerRef.current)
    }

    autoBackupTimerRef.current = setTimeout(() => {
      autoBackupTimerRef.current = null
      void runAutomaticBackup()
    }, 1200)
  }

  async function runAutomaticBackup() {
    if (autoBackupRunningRef.current) {
      autoBackupRetryRequestedRef.current = true
      return
    }

    if (dataTransferActionRef.current) {
      autoBackupRetryRequestedRef.current = true
      scheduleAutomaticBackup()
      return
    }

    const connection = backupConnectionRef.current

    if (!connection?.configured || !connection?.connected) {
      return
    }

    autoBackupRunningRef.current = true
    autoBackupRetryRequestedRef.current = false

    try {
      const backup = await exportDatabaseBackup()
      await uploadBackupToSupabase(backup)
      autoBackupFailureAlertedRef.current = false
      await refreshBackupConnection()
    } catch (error) {
      if (!autoBackupFailureAlertedRef.current) {
        autoBackupFailureAlertedRef.current = true
        Alert.alert(
          'Automatic backup paused',
          error.message || 'The latest backup could not be uploaded to Supabase. Automatic backup will resume after reconnecting, and you can still use manual upload from Settings.'
        )
      }
    } finally {
      autoBackupRunningRef.current = false

      if (autoBackupRetryRequestedRef.current) {
        autoBackupRetryRequestedRef.current = false
        scheduleAutomaticBackup()
      }
    }
  }

  async function ensureBackupConnection(nextAction) {
    if (!isSupabaseBackupConfigured()) {
      Alert.alert(
        'Supabase backup not configured',
        'Add EXPO_PUBLIC_SUPABASE_URL and EXPO_PUBLIC_SUPABASE_PUBLISHABLE_KEY to enable cloud backup and restore.'
      )
      return false
    }

    const connection = await refreshBackupConnection()

    if (connection.connected) {
      return true
    }

    setPendingBackupAction(nextAction)
    openBackupAccountSheet(nextAction === 'restore' ? 'signIn' : 'signUp')
    return false
  }

