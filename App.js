  async function bootstrap() {
    let startupRestoreError = null

    try {
      await initializeDatabase()

      try {
        const connection = await refreshBackupConnection()

        if (connection.connected) {
          try {
            setBlockingLoader({
              title: 'Loading cloud backup',
              body: 'Downloading the latest Supabase backup for this device.',
            })
            const latestBackup = await downloadBackupFromSupabase()
            setBlockingLoader({
              title: 'Restoring cloud backup',
              body: 'Applying the downloaded backup to your local billing data.',
            })
            await replaceDatabaseWithBackup(latestBackup.contents)
          } catch (error) {
            const errorMessage = String(error?.message || '').toLowerCase()

            if (!errorMessage.includes('no supabase backup was found')) {
              startupRestoreError = error
            }
          }
        }
      } catch (_error) {
        setBackupConnection({
          configured: isSupabaseBackupConfigured(),
          connected: false,
          email: '',
          userId: '',
        })
      }

      await refreshRecords()
      setLoadError('')
      setIsReady(true)
      setBlockingLoader(null)

      if (startupRestoreError) {
        Alert.alert(
          'Cloud restore unavailable',
          startupRestoreError.message || 'The latest Supabase backup could not be restored on app open. Local data is still available on this device.'
        )
      }
    } catch (error) {
      setLoadError(error.message || 'Unable to open the local billing database.')
      setIsReady(true)
      setBlockingLoader(null)
    }
  }

