  function addItem() {
    const currentItems = invoice?.items || []
    const lastItem = currentItems[currentItems.length - 1]

    if (lastItem) {
      const missingFields = []

      if (!String(lastItem.description || '').trim()) {
        missingFields.push('description')
      }

      if (!String(lastItem.bagType || '').trim()) {
        missingFields.push('bag type')
      }

      if (normalizeNumber(lastItem.quantity) <= 0) {
        missingFields.push('quantity')
      }

      if (normalizeNumber(lastItem.rate) <= 0) {
        missingFields.push('rate')
      }

      if (missingFields.length > 0) {
        const missingLabel =
          missingFields.length === 1
            ? missingFields[0]
            : `${missingFields.slice(0, -1).join(', ')} and ${missingFields[missingFields.length - 1]}`

        Alert.alert(
          'Complete the current line item',
          `Fill the previous item's ${missingLabel} before adding a new line item.`
        )
        return
      }
    }

    setInvoice((current) => ({
      ...(current || createDraftBill()),
      items: [...(current?.items || []), createItem()],
    }))
  }

