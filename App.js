  function updateField(field, value) {
    setInvoice((current) => {
      const baseInvoice = current || createDraftBill()
      const nextInvoice = {
        ...baseInvoice,
        [field]: value,
      }

      const isSavedBill = bills.some((bill) => bill.id === baseInvoice.id)
      if (field === 'invoiceDate' && !isSavedBill && isAutoGeneratedInvoiceNumber(baseInvoice.invoiceNumber)) {
        nextInvoice.invoiceNumber = getNextInvoiceNumber(bills, value, baseInvoice.id)
      }

      if (field === 'invoiceDate' && nextInvoice.dueDate && !isDueDateAfterInvoiceDate(value, nextInvoice.dueDate)) {
        nextInvoice.dueDate = getMinimumDueDate(value)
      }

      if (field === 'dueDate' && value && !isDueDateAfterInvoiceDate(nextInvoice.invoiceDate, value)) {
        nextInvoice.dueDate = getMinimumDueDate(nextInvoice.invoiceDate)
      }

      return nextInvoice
    })
  }

