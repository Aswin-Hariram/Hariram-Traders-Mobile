  async function submitBackupAccount() {
    setIsBackupAccountSubmitting(true)

    try {
      if (backupAccountMode === 'signUp') {
        const signUpResult = await signUpSupabaseBackupAccount(backupAccountEmail, backupAccountPassword)

        if (signUpResult.requiresEmailConfirmation) {
          setBackupAccountMode('signIn')
          setBackupAccountPassword('')
          Alert.alert(
            'Confirm your email',
            `Supabase sent a confirmation email to ${signUpResult.email}. Confirm it first, then sign in here to continue with backup or restore.`
          )
          return
        }
      } else {
        await signInSupabaseBackupAccount(backupAccountEmail, backupAccountPassword)
      }

      const connection = await refreshBackupConnection()
      const nextAction = pendingBackupAction

      setPendingBackupAction(null)
      setIsBackupAccountSheetOpen(false)
      setBackupAccountPassword('')

      if (nextAction === 'export') {
        await handleExportBackup()
        return
      }

      if (nextAction === 'restore') {
        await handleRestoreBackup()
        return
      }

      Alert.alert(
        'Backup account connected',
        `Supabase backup is ready for automatic bill, customer, and settings updates${connection.email ? ` on ${connection.email}` : ''}.`
      )
    } catch (error) {
      Alert.alert(
        backupAccountMode === 'signUp' ? 'Unable to create backup account' : 'Unable to sign in',
        error.message || 'Please try again.'
      )
    } finally {
      setIsBackupAccountSubmitting(false)
    }
  }

